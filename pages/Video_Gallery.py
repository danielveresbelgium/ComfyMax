from __future__ import annotations

import json
import os
import subprocess
from datetime import datetime, timedelta
from pathlib import Path

import streamlit as st


# ============================================================
# Paths and configuration
# ============================================================

ROOT = Path(__file__).resolve().parents[1]
CONFIG_DIR = ROOT / "config"
SETTINGS_PATH = CONFIG_DIR / "settings.json"

VIDEO_EXTENSIONS = {".mp4", ".webm", ".mov", ".mkv", ".avi", ".m4v"}


# ============================================================
# Helpers
# ============================================================

def load_settings() -> dict:
    if not SETTINGS_PATH.exists():
        return {}

    try:
        data = json.loads(SETTINGS_PATH.read_text(encoding="utf-8"))
        return data if isinstance(data, dict) else {}
    except (OSError, json.JSONDecodeError):
        return {}


def human_file_size(size_bytes: int) -> str:
    size = float(size_bytes)

    for unit in ("B", "KB", "MB", "GB", "TB"):
        if size < 1024 or unit == "TB":
            if unit == "B":
                return f"{int(size)} B"
            return f"{size:.1f} {unit}"
        size /= 1024

    return f"{size_bytes} B"


def scan_videos(folder: Path) -> list[dict]:
    videos: list[dict] = []

    if not folder.exists() or not folder.is_dir():
        return videos

    try:
        candidates = folder.rglob("*")
    except OSError:
        return videos

    for path in candidates:
        try:
            if not path.is_file():
                continue

            if path.suffix.lower() not in VIDEO_EXTENSIONS:
                continue

            stat = path.stat()

            videos.append(
                {
                    "path": path,
                    "name": path.name,
                    "relative": str(path.relative_to(folder)),
                    "modified": datetime.fromtimestamp(stat.st_mtime),
                    "size": stat.st_size,
                }
            )

        except (OSError, ValueError):
            continue

    videos.sort(
        key=lambda item: item["modified"],
        reverse=True,
    )

    return videos


def open_in_explorer(path: Path) -> None:
    if os.name == "nt":
        subprocess.Popen(
            ["explorer", "/select,", str(path)],
            creationflags=getattr(
                subprocess,
                "CREATE_NO_WINDOW",
                0,
            ),
        )
        return

    if os.name == "posix":
        subprocess.Popen(["xdg-open", str(path.parent)])
        return

    raise RuntimeError("Opening the file location is not supported on this system.")


def matches_date_filter(modified: datetime, filter_name: str) -> bool:
    now = datetime.now()

    if filter_name == "Today":
        return modified.date() == now.date()

    if filter_name == "This week":
        return modified >= now - timedelta(days=7)

    if filter_name == "This month":
        return modified >= now - timedelta(days=30)

    return True


def delete_video(path: Path) -> None:
    path.unlink()


